//! 作用域端口：取代贯穿一切实现细节的 `workspace: &Path`。
//!
//! coding 助手的"作用域"是工作区目录；生活类助手可能是"用户数据根 + 资源白名单"；
//! 通用助手可能只是一个会话沙箱。内核只要求两件事：**一个稳定标识** + **一次路径解析**。
//!
//! 路径解析只负责"相对路径落在哪、符号链接指向哪"，**不负责允许/拒绝**。

use std::path::PathBuf;

pub trait Scope: Send + Sync {
    /// 稳定标识（用于落盘分组、日志、事件归属）。
    fn id(&self) -> &str;

    /// 把外部传入的路径解析成真实路径（相对路径以作用域根为基准）。
    ///
    /// 解析永远不会因为"越界"而失败：访问边界不再由基座裁决，需要策略时由插件事件
    /// （`event_before_*`）决定。
    fn resolve_path(&self, raw: &str) -> PathBuf;
}
