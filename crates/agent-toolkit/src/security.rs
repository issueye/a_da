//! 安全策略的**临时总开关**（2026-10-27）。
//!
//! # 为什么有它
//!
//! 快速落地阶段，审批、路径沙箱、插件能力门与危险命令扫描一律不阻塞功能：
//! 每加一个能力都先过一遍安全评审，结果是"功能一直让渡给安全"。
//! 本模块把这些机制的**执行**集中到一个开关上：
//!
//! - `SECURITY_ENFORCED = false`（当前）：生产路径全部放行；
//! - 改成 `true`：恢复原有语义（审批、沙箱、能力门、危险命令扫描）。
//!
//! # 这不是删除
//!
//! 端口、策略函数、UI、协议与测试都保留。恢复只需改这一个常量并跑
//! `cargo test --workspace -- --test-threads=1`。物理删除是 P3 的独立工作
//! （见 `docs/architecture/PLAN-pluginization.md` §4.6）。
//!
//! # 仍然保留的底线
//!
//! 1. `~/.a-da` 里的**凭据与配置**仍不可写（`ApprovalAwareScope` 的黑名单）——
//!    那是数据完整性，不是"要不要问用户"；
//! 2. 工具回执、事件顺序、取消贯穿、描述符单一真源等**契约**不受影响。
//!
//! 它们不是审批/安全闸门；关掉会让界面与模型同时收到假信息。
//!
//! # 只允许在「执行边界」读取
//!
//! 纯函数（`should_ask_approval_*`、`check_workspace_sandbox`）保持原语义，
//! 由宿主决定是否走直通实现。这样单元测试仍然描述"启用安全时"的行为，
//! 而不是让开关渗进每个判定函数。

/// 是否执行审批 / 路径沙箱 / 插件能力门 / 危险命令扫描。
///
/// 临时值：`false`（安全机制整体下线）。恢复安全：改成 `true`。
pub const SECURITY_ENFORCED: bool = false;

/// 便捷判断（读起来比 `!SECURITY_ENFORCED` 清楚）。
pub const fn deferred() -> bool {
    !SECURITY_ENFORCED
}
